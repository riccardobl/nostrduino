#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
unit_test_dir="$repo_root/tests/unit"
wokwi_project_dir="$repo_root/wokwi/esp32"
unit_test_env="${UNIT_TEST_ENV:-UnitTests}"
if [[ ! "$unit_test_env" =~ ^[A-Za-z0-9_]+$ ]]; then
    echo "Invalid UNIT_TEST_ENV: $unit_test_env" >&2
    exit 2
fi
artifact_dir="$repo_root/.pio/build/$unit_test_env"
registry_file="$unit_test_dir/test_registry.generated.inc"
results_file="${UNIT_TEST_RESULTS_FILE:-}"
output_file="${UNIT_TEST_OUTPUT_FILE:-}"
timeout_ms="${UNIT_TEST_TIMEOUT_MS:-60000}"
timeout_seconds="$(( (timeout_ms + 999) / 1000 ))"
wokwi_cli="${WOKWI_CLI:-wokwi-cli}"
qemu_bin="${QEMU_SYSTEM_XTENSA:-qemu-system-xtensa}"
emulator="${UNIT_TEST_EMULATOR:-auto}"
serial_log="$(mktemp "${TMPDIR:-/tmp}/nostrduino-unit-tests.XXXXXX.log")"
qemu_flash="$artifact_dir/qemu_flash.bin"
unit_test_names=()
unit_test_functions=()
unit_test_compiled="FALSE"

discover_unit_tests() {
    local test_source file_name test_name function_matches function_count test_function
    local test_sources=()

    shopt -s nullglob
    test_sources=("$unit_test_dir"/test_*.cpp)
    shopt -u nullglob

    for test_source in "${test_sources[@]}"; do
        file_name="$(basename "$test_source")"
        case "$file_name" in
            test_unit.cpp|test_support.cpp)
                continue
                ;;
        esac

        test_name="${file_name#test_}"
        test_name="${test_name%.cpp}"
        if [[ ! "$test_name" =~ ^[a-z0-9_]+$ ]]; then
            echo "Unsupported unit-test filename: $file_name" >&2
            exit 1
        fi

        function_matches="$(sed -nE 's/^[[:space:]]*bool[[:space:]]+(test[A-Za-z0-9_]*)[[:space:]]*\([[:space:]]*\)[[:space:]]*\{.*/\1/p' "$test_source")"
        function_count="$(printf '%s\n' "$function_matches" | grep -c . || true)"
        if [[ "$function_count" -ne 1 ]]; then
            echo "Expected exactly one bool test...() entrypoint in $file_name, found $function_count" >&2
            exit 1
        fi
        test_function="$function_matches"

        unit_test_names+=("$test_name")
        unit_test_functions+=("$test_function")
    done

    if [[ "${#unit_test_names[@]}" -eq 0 ]]; then
        echo "No unit tests discovered in $unit_test_dir" >&2
        exit 1
    fi

    {
        printf '%s\n' '// Generated by tests/unit/run.sh. Do not edit.'
        for test_index in "${!unit_test_names[@]}"; do
            printf 'NOSTRDUINO_DISCOVERED_TEST("%s", %s)\n' \
                "${unit_test_names[$test_index]}" "${unit_test_functions[$test_index]}"
        done
    } > "$registry_file"
}

write_unit_test_results() {
    local test_name compiled executed correct state

    if [[ -n "$results_file" ]]; then
        : > "$results_file"
        for test_name in "${unit_test_names[@]}"; do
            compiled="$unit_test_compiled"
            executed="FALSE"
            correct="FALSE"
            state="FALSE"
            if grep -Fq "UNIT_TEST $test_name PASS" "$serial_log"; then
                executed="OK"
                correct="OK"
                state="OK"
            elif grep -Fq "UNIT_TEST $test_name FAIL" "$serial_log"; then
                executed="OK"
            fi
            printf '%s\t%s\t%s\t%s\t%s\n' \
                "$test_name" "$compiled" "$executed" "$correct" "$state" >> "$results_file"
        done
    fi

    if [[ -n "$output_file" ]]; then
        if ! grep -E 'UNIT_(TEST|ASSERT)' "$serial_log" > "$output_file"; then
            printf '%s\n' '(nessun risultato seriale prodotto)' > "$output_file"
        fi
    fi
}

cleanup() {
    local run_status=$?
    trap - EXIT
    if ! write_unit_test_results; then
        run_status=1
    fi
    rm -f -- "$registry_file" "$serial_log"
    exit "$run_status"
}

trap cleanup EXIT

discover_unit_tests

if ! command -v pio >/dev/null 2>&1; then
    echo "PlatformIO is required for ESP32 unit tests" >&2
    exit 2
fi
cd "$repo_root"
pio pkg install -e "$unit_test_env"
pio run -e "$unit_test_env" -t clean
build_started_at="$(date +%s)"
pio run -e "$unit_test_env"

for artifact in "$artifact_dir/firmware.elf" "$artifact_dir/firmware.bin"; do
    test -s "$artifact"
    artifact_mtime="$(stat -c '%Y' "$artifact")"
    if (( artifact_mtime < build_started_at )); then
        echo "Unit-test artifact was not produced by the current build: $artifact" >&2
        exit 1
    fi
done
unit_test_compiled="OK"

case "$emulator" in
    auto)
        if [[ -n "${WOKWI_CLI_TOKEN:-}" ]]; then
            emulator="wokwi"
        else
            emulator="qemu"
        fi
        ;;
    wokwi|qemu)
        ;;
    *)
        echo "UNIT_TEST_EMULATOR must be auto, wokwi, or qemu" >&2
        exit 2
        ;;
esac

if [[ "$emulator" == "wokwi" ]]; then
    if ! command -v "$wokwi_cli" >/dev/null 2>&1; then
        echo "wokwi-cli is required for UNIT_TEST_EMULATOR=wokwi" >&2
        exit 2
    fi
    if [[ -z "${WOKWI_CLI_TOKEN:-}" ]]; then
        echo "WOKWI_CLI_TOKEN is required for UNIT_TEST_EMULATOR=wokwi" >&2
        exit 2
    fi

    set +e
    "$wokwi_cli" \
        --timeout "$timeout_ms" \
        --expect-text "UNIT_TESTS PASSED" \
        --fail-text "UNIT_TESTS FAILED" \
        --serial-log-file "$serial_log" \
        "$wokwi_project_dir"
    emulator_status=$?
    set -e
else
    if [[ "$qemu_bin" == */* ]]; then
        qemu_command="$qemu_bin"
    else
        qemu_command="$(command -v "$qemu_bin" || true)"
    fi
    if [[ -z "$qemu_command" || ! -x "$qemu_command" ]]; then
        echo "Espressif qemu-system-xtensa is required for UNIT_TEST_EMULATOR=qemu" >&2
        echo "Install the official Espressif QEMU fork or set QEMU_SYSTEM_XTENSA to its binary." >&2
        exit 2
    fi

    esptool="${ESPTOOL:-}"
    if [[ -z "$esptool" ]]; then
        esptool="$(command -v esptool.py || true)"
    fi
    if [[ -z "$esptool" ]]; then
        esptool="$(find "${PLATFORMIO_CORE_DIR:-$HOME/.platformio}/packages" -path '*/tool-esptoolpy/esptool.py' -type f -print -quit 2>/dev/null || true)"
    fi
    if [[ -z "$esptool" ]]; then
        echo "esptool.py is required to assemble the QEMU flash image" >&2
        exit 2
    fi
    python3 "$esptool" --chip esp32 merge_bin --fill-flash-size 4MB -o "$qemu_flash" \
        0x1000 "$artifact_dir/bootloader.bin" \
        0x8000 "$artifact_dir/partitions.bin" \
        0x10000 "$artifact_dir/firmware.bin"

    if [[ "$(uname -s)" == "Darwin" ]]; then
        # Let macOS finish publishing the freshly rewritten mmap-backed image.
        sync
        sleep "${UNIT_TEST_QEMU_SETTLE_SECONDS:-2}"
    fi

    run_qemu() {
        timeout --signal=TERM "${timeout_seconds}s" "$qemu_command" \
            -nographic \
            -machine esp32 \
            -drive "file=$qemu_flash,if=mtd,format=raw" \
            -global driver=timer.esp32.timg,property=wdt_disable,value=true \
            >"$serial_log" 2>&1
    }

    set +e
    run_qemu
    emulator_status=$?
    if (( emulator_status == 134 )) && ! grep -Fq "UNIT_TEST " "$serial_log"; then
        # The arm64 macOS build can occasionally abort during QEMU startup.
        # Retry once, but never mask a boot that produced test output.
        sleep 1
        run_qemu
        emulator_status=$?
    fi
    set -e
fi

if (( emulator_status != 0 && emulator_status != 124 )); then
    echo "$emulator emulator failed with exit code $emulator_status" >&2
    exit "$emulator_status"
fi

for test_name in "${unit_test_names[@]}"; do
    marker="UNIT_TEST $test_name PASS"
    if ! grep -Fq "$marker" "$serial_log"; then
        echo "Missing $emulator serial marker: $marker" >&2
        exit 1
    fi
done

if ! grep -Fq "UNIT_TESTS PASSED" "$serial_log"; then
    echo "Missing $emulator serial marker: UNIT_TESTS PASSED" >&2
    exit 1
fi

if grep -Fq "UNIT_TESTS FAILED" "$serial_log"; then
    echo "$emulator reported a failing unit test" >&2
    exit 1
fi

echo "$emulator ESP32 unit tests passed"
